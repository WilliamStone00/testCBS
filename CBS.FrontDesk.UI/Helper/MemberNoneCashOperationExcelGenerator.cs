using CBS.FrontDesk.Data.Entity.MemberNoneCashOperationsP;
using ClosedXML.Excel;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Web;

namespace CBS.FrontDesk.UI.Helper
{
    public static class MemberNoneCashOperationExcelGenerator
    {
        public static void GenerateOperationExcel(List<MemberNoneCashOperation> operations, string exportPath, string exportDate, string exportedBy, string statusTitle)
        {
            using (var workbook = new XLWorkbook())
            {
                var worksheet = workbook.Worksheets.Add("Operations");

                // Dynamic Title based on status
                worksheet.Cell(1, 1).Value = $"{statusTitle} Member None-Cash Operations";
                worksheet.Cell(1, 1).Style.Font.Bold = true;
                worksheet.Cell(1, 1).Style.Font.FontSize = 14;
                worksheet.Range(1, 1, 1, 10).Merge();
                worksheet.Cell(1, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;

                // Export Details
                worksheet.Cell(2, 1).Value = $"Export Date: {exportDate} | Exported By: {exportedBy}";
                worksheet.Cell(2, 1).Style.Font.Italic = true;
                worksheet.Cell(2, 1).Style.Font.FontSize = 10;
                worksheet.Range(2, 1, 2, 10).Merge();
                worksheet.Cell(2, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;

                // Headers
                var headers = new[]
                {
            "Member Reference", "Member Name", "Account Number", "Chart of Account", "Amount",
            "Booking Direction", "Request Date", "Approval Status", "Initiated By", "Note"
        };

                for (int i = 0; i < headers.Length; i++)
                {
                    worksheet.Cell(4, i + 1).Value = headers[i];
                    worksheet.Cell(4, i + 1).Style.Font.Bold = true;
                    worksheet.Cell(4, i + 1).Style.Fill.BackgroundColor = XLColor.LightGray;
                    worksheet.Cell(4, i + 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    worksheet.Cell(4, i + 1).Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                }

                // Data rows
                int currentRow = 5;
                foreach (var operation in operations)
                {
                    worksheet.Cell(currentRow, 1).Value = operation.MemberReference;
                    worksheet.Cell(currentRow, 2).Value = operation.MemberName;
                    worksheet.Cell(currentRow, 3).Value = operation.AccountNUmber;
                    worksheet.Cell(currentRow, 4).Value = operation.ChartOfAccountName;
                    worksheet.Cell(currentRow, 5).Value = operation.Amount;
                    worksheet.Cell(currentRow, 6).Value = operation.BookingDirection;
                    worksheet.Cell(currentRow, 7).Value = operation.RequestDate.ToString("dd/MM/yyyy HH:mm");
                    worksheet.Cell(currentRow, 8).Value = operation.ApprovalStatus ?? "Pending";
                    worksheet.Cell(currentRow, 9).Value = operation.InitiatedUserName;
                    worksheet.Cell(currentRow, 10).Value = operation.Note;

                    // Format currency fields (Amount)
                    worksheet.Cell(currentRow, 5).Style.NumberFormat.Format = "#,##0";

                    // Styling
                    for (int col = 1; col <= 10; col++)
                    {
                        worksheet.Cell(currentRow, col).Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                    }

                    currentRow++;
                }

                // Footer row for totals (Sum of amounts)
                worksheet.Cell(currentRow, 4).Value = "TOTAL";
                worksheet.Cell(currentRow, 4).Style.Font.Bold = true;
                worksheet.Cell(currentRow, 4).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                worksheet.Cell(currentRow, 4).Style.Fill.BackgroundColor = XLColor.LightGray;
                worksheet.Cell(currentRow, 4).Style.Border.OutsideBorder = XLBorderStyleValues.Thin;

                worksheet.Cell(currentRow, 5).FormulaA1 = $"SUM(E5:E{currentRow - 1})";
                worksheet.Cell(currentRow, 5).Style.Font.Bold = true;
                worksheet.Cell(currentRow, 5).Style.NumberFormat.Format = "#,##0";  // Total amount in currency format
                worksheet.Cell(currentRow, 5).Style.Fill.BackgroundColor = XLColor.LightGray;
                worksheet.Cell(currentRow, 5).Style.Border.OutsideBorder = XLBorderStyleValues.Thin;

                currentRow++;

                // Footer Section for Signature or Extra Information
                worksheet.Cell(currentRow, 1).Value = "Generated by @Trust Soft Credit.";
                worksheet.Cell(currentRow, 1).Style.Font.Italic = true;
                worksheet.Cell(currentRow, 1).Style.Font.FontSize = 10;
                worksheet.Range(currentRow, 1, currentRow, 10).Merge();
                worksheet.Cell(currentRow, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;

                // Adjust column widths
                worksheet.Columns().AdjustToContents();

                // Save the file
                workbook.SaveAs(exportPath);
            }
        }
    }

}